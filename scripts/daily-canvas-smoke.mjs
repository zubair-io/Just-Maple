/** Explicit synthetic canvas acceptance; no real inbox, provider, iCloud or running Mac app is touched. */
import { chromium, expect } from '../src/web/node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { syntheticBridge } from './today-synthetic-bridge.mjs';
const output='.build/daily-canvas-smoke';
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1600,height:1100},timezoneId:'America/New_York'});
await context.addInitScript(syntheticBridge);
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
const editor=page.getByRole('textbox',{name:'Daily note editor',exact:true});
const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('maple.today.sources.smoke.v1')));
try {
  await page.goto((process.env.MAPLE_SMOKE_URL||'http://127.0.0.1:4327')+'/#/today');
  await expect(page.getByRole('button',{name:'Canvas',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(editor.locator('[data-canvas-id]')).toHaveCount(4);
  await editor.evaluate(el=>window.__originalCanvasEditor=el);
  await page.getByRole('button',{name:'＋ Sticky',exact:true}).click();
  await page.keyboard.type('Synthetic sticky: buy maple syrup.');
  await expect.poll(async()=>(await saved()).content).toContain('Synthetic sticky: buy maple syrup.');
  await page.getByRole('button',{name:'¶ Note',exact:true}).click();
  await page.keyboard.type('Synthetic long-form note.');await page.keyboard.press('Enter');await page.keyboard.type('Second paragraph stays in this card.');
  await expect.poll(async()=>(await saved()).content).toContain('Second paragraph stays in this card.');
  await page.getByRole('button',{name:'☑ Action',exact:true}).click();
  await expect(editor).toContainText('New action item');
  await page.getByRole('button',{name:'Deselect',exact:true}).click();
  const sticky=page.getByRole('button',{name:'Select card: Synthetic sticky: buy maple syrup.',exact:true});
  const writing=page.getByRole('button',{name:'Select card: Synthetic long-form note.Second paragraph stays in this card.',exact:true});
  await sticky.click();await writing.click();
  await page.getByRole('textbox',{name:'Group name',exact:true}).fill('Synthetic errands');
  await page.getByRole('button',{name:'Box together',exact:true}).click();
  await expect(page.getByRole('region',{name:'Synthetic errands',exact:true})).toBeVisible();
  const groupHandle=page.getByRole('button',{name:'Move group: Synthetic errands',exact:true});
  const beforeKey=await page.locator('.canvas-group').evaluate(el=>Number.parseFloat(el.style.left));
  await groupHandle.focus();await page.keyboard.press('ArrowRight');
  await expect.poll(()=>page.locator('.canvas-group').evaluate(el=>Number.parseFloat(el.style.left))).toBe(beforeKey+16);
  const beforeDrag=await page.locator('.canvas-group').evaluate(el=>Number.parseFloat(el.style.left));
  const handleBounds=await groupHandle.boundingBox();
  await page.mouse.move(handleBounds.x+handleBounds.width/2,handleBounds.y+handleBounds.height/2);
  await page.mouse.down();await page.mouse.move(handleBounds.x+handleBounds.width/2+48,handleBounds.y+handleBounds.height/2+32,{steps:5});await page.mouse.up();
  await expect.poll(()=>page.locator('.canvas-group').evaluate(el=>Number.parseFloat(el.style.left))).toBe(beforeDrag+48);

  await page.getByRole('button',{name:'Collapse Synthetic errands',exact:true}).click();
  await expect(editor.locator('[data-canvas-folded="true"]')).toHaveCount(2);
  await expect.poll(async()=>(await saved()).content).toContain('"folded":true');
  await page.reload();
  await expect(editor.locator('[data-canvas-folded="true"]')).toHaveCount(2);
  await page.getByRole('button',{name:'Expand Synthetic errands',exact:true}).click();
  await page.getByRole('button',{name:'Note',exact:true}).click();
  await expect(editor).toContainText('Synthetic long-form note.');
  await expect(editor.locator('.maple-canvas-card')).toHaveCount(0);
  await editor.evaluate(el=>window.__originalCanvasEditor=el);
  await page.getByRole('button',{name:'Canvas',exact:true}).click();
  assert.equal(await editor.evaluate(el=>el===window.__originalCanvasEditor),true,'view switching must preserve the live editor');
  await page.getByRole('button',{name:'Fit',exact:true}).click();
  await page.screenshot({path:output+'/canvas-light.png',fullPage:true});
  await page.evaluate(()=>{document.documentElement.classList.add('dark');document.documentElement.setAttribute('data-theme','dark');});
  await expect(page.getByRole('button',{name:'＋ Sticky',exact:true})).toHaveCSS('color','rgb(231, 229, 228)');
  await page.screenshot({path:output+'/canvas-dark.png',fullPage:true});
  await page.getByRole('button',{name:'Select all',exact:true}).click();
  const callsBefore=(await saved()).calls.filter(c=>c==='mapleSubmit').length;
  await page.getByRole('button',{name:'Ask about selection',exact:true}).click();
  await expect.poll(async()=>(await saved()).content).toContain('contextBlockIDs');
  assert.equal((await saved()).calls.filter(c=>c==='mapleSubmit').length,callsBefore,'creating a selection request must not submit it');
  assert.deepEqual(errors,[]);
  await fs.writeFile(output+'/result.json',JSON.stringify({fixture:true,checks:['sticky typing and autosave','multi-paragraph writing card','local action checklist','selection and named group','keyboard and pointer group movement','collapse and reload persistence','Note/Canvas same editor','fit and light/dark screenshots','selected-card request remains unsubmitted'],errors},null,2));
  console.log('Synthetic daily canvas acceptance passed. Evidence: '+output);
} finally {await browser.close();}
